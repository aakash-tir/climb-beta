"""Generate the Label Studio labelling config from configs/colours.yaml + classes.yaml.

The colour list lives in one place (configs/colours.yaml). Edit it, then run
`python labelling/make_config.py` to regenerate labelling/label_config.xml.

Layout:
- BrushLabels (`mask`): where SAM 2 returns masks; can also be hand-painted.
- PolygonLabels (`poly`): hand-drawn outlines, for when SAM struggles.
- KeyPointLabels / RectangleLabels with smart="true": click/box prompts for SAM 2.
- Per-region Choices: hold colour (single), and a "chalked" flag. Shown when a region is
  selected, so every hold mask carries its own colour.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from collections.abc import Sequence

from climb_beta.config import ColourConfig
from climb_beta.labelling import schema

CLASS_COLOURS = {"hold": "#ff4d4f", "volume": "#40a9ff", "tape": "#fadb14"}
INSTRUCTIONS = (
    "Outline every hold, volume and tape diamond. Click a hold to prompt SAM 2 "
    "(or drag a box), check the mask, then with the region selected pick its colour and "
    "tick 'chalked' if chalk covers a visible part of it. Tape diamonds get their colour "
    "too (it is the route's grade). Volumes need no colour."
)


def _labels(parent: ET.Element, tag: str, name: str, classes: Sequence[str], **attrs: str) -> None:
    el = ET.SubElement(parent, tag, {"name": name, "toName": schema.IMAGE, **attrs})
    for c in classes:
        ET.SubElement(el, "Label", {"value": c, "background": CLASS_COLOURS.get(c, "#999999")})


def build_config(classes: Sequence[str], cfg: ColourConfig) -> str:
    view = ET.Element("View")
    ET.SubElement(view, "Header", {"value": INSTRUCTIONS})
    ET.SubElement(
        view,
        "Image",
        {
            "name": schema.IMAGE,
            "value": "$image",
            "zoom": "true",
            "zoomControl": "true",
            "brightnessControl": "true",
            "contrastControl": "true",
        },
    )
    _labels(view, "BrushLabels", schema.BRUSH, classes)
    _labels(view, "PolygonLabels", schema.POLYGON, classes, strokeWidth="2", pointSize="small")
    _labels(view, "KeyPointLabels", schema.KEYPOINT, classes, smart="true")
    _labels(view, "RectangleLabels", schema.RECT, classes, smart="true")

    region = ET.SubElement(view, "View", {"visibleWhen": "region-selected"})
    ET.SubElement(region, "Header", {"value": "Colour (hold, or tape diamond = grade)"})
    colour = ET.SubElement(
        region,
        "Choices",
        {
            "name": schema.COLOUR,
            "toName": schema.IMAGE,
            "perRegion": "true",
            "choice": "single-radio",
            "showInline": "true",
        },
    )
    for c in cfg.colours:
        ET.SubElement(colour, "Choice", {"value": c.name, "background": c.swatch})
    chalk = ET.SubElement(
        region,
        "Choices",
        {"name": schema.CHALKED, "toName": schema.IMAGE, "perRegion": "true", "choice": "multiple"},
    )
    ET.SubElement(chalk, "Choice", {"value": schema.CHALKED_VALUE})

    ET.indent(view, space="  ")
    header = (
        "<!-- GENERATED by labelling/make_config.py from configs/colours.yaml and "
        "configs/classes.yaml. Do not edit by hand. -->\n"
    )
    return header + ET.tostring(view, encoding="unicode") + "\n"
