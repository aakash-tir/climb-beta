"""Split Basecamp photos into train/val/test **by wall**.

Photos of the same wall share holds, angle and lighting. A photo-level split would
put near-duplicates of test images in train and inflate every metric. A wall is
the unit: all of its photos go to exactly one split.

Layout (photos and labels are gitignored and synced to a private HF dataset):

    data/basecamp/raw/<wall_id>/<photo>.jpg
    data/basecamp/labels/<wall_id>/<photo>.txt        YOLO-seg (from Label Studio)
    data/basecamp/labels/<wall_id>/<photo>.json       colour sidecar
    data/basecamp/walls.yaml                          committed: wall metadata
    data/basecamp/splits.yaml                         committed: {train/val/test: [walls]}
"""

from __future__ import annotations

import json
import random
import shutil
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from climb_beta.data.coco_to_yolo import write_dataset_yaml

SPLITS = ("train", "val", "test")
IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".webp"}


class SplitError(ValueError):
    pass


def assign_walls(
    photo_counts: Mapping[str, int],
    ratios: tuple[float, float, float] = (0.7, 0.15, 0.15),
    seed: int = 0,
) -> dict[str, list[str]]:
    """Deterministically assign whole walls to splits, aiming at `ratios` of photos.

    With 3+ walls, val and test each get at least one wall. Walls are shuffled with
    `seed`, then each goes to the split furthest below its target photo share.
    """
    if abs(sum(ratios) - 1.0) > 1e-6 or min(ratios) < 0:
        raise SplitError(f"ratios must be >= 0 and sum to 1, got {ratios}")
    walls = sorted(photo_counts)
    random.Random(seed).shuffle(walls)
    out: dict[str, list[str]] = {s: [] for s in SPLITS}
    got = dict.fromkeys(SPLITS, 0)
    total = sum(photo_counts.values()) or 1
    queue = list(walls)
    if len(queue) >= 3:  # seed each held-out split first so none is empty
        for s in ("test", "val", "train"):
            w = queue.pop(0)
            out[s].append(w)
            got[s] += photo_counts[w]
    for w in queue:
        deficits = {s: r * total - got[s] for s, r in zip(SPLITS, ratios, strict=True) if r > 0}
        s = max(deficits, key=lambda k: (deficits[k], -SPLITS.index(k)))
        out[s].append(w)
        got[s] += photo_counts[w]
    return {s: sorted(v) for s, v in out.items()}


def validate_splits(splits: Mapping[str, Sequence[str]]) -> dict[str, str]:
    """Check a {split: [walls]} mapping and return wall -> split. Raises on overlap."""
    unknown = set(splits) - set(SPLITS)
    if unknown:
        raise SplitError(f"unknown split names: {sorted(unknown)}")
    wall_to_split: dict[str, str] = {}
    for s in SPLITS:
        for w in splits.get(s, []) or []:
            if w in wall_to_split:
                raise SplitError(f"wall '{w}' is in both '{wall_to_split[w]}' and '{s}'")
            wall_to_split[w] = s
    return wall_to_split


def load_splits(path: Path) -> dict[str, list[str]]:
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    splits = {s: list(raw.get(s) or []) for s in raw}
    validate_splits(splits)
    return {s: splits.get(s, []) for s in SPLITS}


def save_splits(path: Path, splits: Mapping[str, Sequence[str]]) -> None:
    validate_splits(splits)
    header = "# Wall -> split. Generated by data/split_by_wall.py; a wall may appear only once.\n"
    body = yaml.safe_dump({s: list(splits.get(s, [])) for s in SPLITS}, sort_keys=False)
    path.write_text(header + body, encoding="utf-8")


def scan_walls(raw_root: Path) -> dict[str, list[Path]]:
    """wall_id -> sorted photo paths under raw_root/<wall_id>/."""
    out: dict[str, list[Path]] = {}
    for d in sorted(p for p in raw_root.iterdir() if p.is_dir() and not p.name.startswith(".")):
        photos = sorted(p for p in d.iterdir() if p.suffix.lower() in IMAGE_EXTS)
        if photos:
            out[d.name] = photos
    return out


@dataclass
class BuildReport:
    images: dict[str, int] = field(default_factory=lambda: dict.fromkeys(SPLITS, 0))
    unlabelled: list[str] = field(default_factory=list)
    unassigned_walls: list[str] = field(default_factory=list)
    pseudo_skipped_from_test: list[str] = field(default_factory=list)
    manifest: list[dict[str, Any]] = field(default_factory=list)


def build_dataset(
    raw_root: Path,
    labels_root: Path,
    splits: Mapping[str, Sequence[str]],
    out: Path,
    classes: Sequence[str],
    pseudo: set[str] | None = None,
) -> BuildReport:
    """Write a YOLO-seg dataset (images/labels/colours per split) from the wall split.

    Output names are `<wall_id>__<photo>` so photos from different walls can't collide.
    `pseudo` lists `wall_id/photo` entries with pseudo-masks; they are never written
    to test. Raises if the written manifest ever puts one wall in two splits.
    """
    wall_to_split = validate_splits(splits)
    pseudo = pseudo or set()
    rep = BuildReport()
    for wall, photos in scan_walls(raw_root).items():
        split = wall_to_split.get(wall)
        if split is None:
            rep.unassigned_walls.append(wall)
            continue
        for photo in photos:
            key = f"{wall}/{photo.name}"
            label = labels_root / wall / (photo.stem + ".txt")
            if not label.exists():
                rep.unlabelled.append(key)
                continue
            if split == "test" and key in pseudo:
                rep.pseudo_skipped_from_test.append(key)
                continue
            name = f"{wall}__{photo.stem}"
            (out / "images" / split).mkdir(parents=True, exist_ok=True)
            (out / "labels" / split).mkdir(parents=True, exist_ok=True)
            shutil.copy2(photo, out / "images" / split / (name + photo.suffix.lower()))
            shutil.copy2(label, out / "labels" / split / (name + ".txt"))
            sidecar = labels_root / wall / (photo.stem + ".json")
            if sidecar.exists():
                (out / "colours" / split).mkdir(parents=True, exist_ok=True)
                shutil.copy2(sidecar, out / "colours" / split / (name + ".json"))
            rep.images[split] += 1
            rep.manifest.append({"image": name, "wall": wall, "split": split})

    seen: dict[str, str] = {}
    for row in rep.manifest:
        prev = seen.setdefault(row["wall"], row["split"])
        if prev != row["split"]:  # can't happen by construction; checked anyway
            raise SplitError(f"wall '{row['wall']}' written to '{prev}' and '{row['split']}'")

    out.mkdir(parents=True, exist_ok=True)
    write_dataset_yaml(out, classes, [s for s in SPLITS if rep.images[s]])
    (out / "manifest.json").write_text(json.dumps(rep.manifest, indent=1), encoding="utf-8")
    return rep
